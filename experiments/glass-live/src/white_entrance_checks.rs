//! Focused entrance review using the actual production shaders and generated input.
//! Bounds below are engineering regressions, NOT measured Apple shader constants.
//! This does not open windows, capture the desktop, or start audio.
use super::*;
use std::io::Write;

// A fixed central blank-material ROI, safely inside even the initial capsule.
// Measure the ink-disabled render, never a moving glyph or a changing edge.
fn body_rgb(bytes: &[u8], width: u32, height: u32) -> [f64; 3] {
    let mut sum = [0.0; 3];
    let mut count = 0;
    for y in height * 2 / 5..height * 3 / 5 {
        for x in width / 3..width * 2 / 3 {
            let p = pixel(bytes, width, x, y);
            for k in 0..3 { sum[k] += p[k] as f64; }
            count += 1;
        }
    }
    sum.map(|value| value / count as f64)
}

fn text_contrast(fg: &[u8], bg: &[u8], mask: &[u8], w: u32, h: u32) -> (usize, f64) {
    // Encoded values of the existing production ink colors; allow rounding by 1.
    let inks = [[25u8, 34, 42], [249, 252, 255]];
    let mut count = 0;
    let mut minimum = f64::INFINITY;
    for y in h / 3..h * 2 / 3 {
        for x in h..w - h / 3 {
            let a = pixel(fg, w, x, y);
            let b = pixel(bg, w, x, y);
            if mask[(y * w + x) as usize] < 254 || a[3] != 255 { continue; }
            if !inks.iter().any(|ink| (0..3).all(|k| a[k].abs_diff(ink[k]) <= 1)) { continue; }
            let ya = luma(a);
            let yb = luma(b);
            minimum = minimum.min((ya.max(yb) + 0.05) / (ya.min(yb) + 0.05));
            count += 1;
        }
    }
    (count, minimum)
}

pub(super) unsafe fn verify(directory: Option<&Path>) -> AppResult<()> {
    let (device, context) = create_device(None)?;
    let (w, h) = (162u32, 39u32);
    let times = [0.0f32, 0.05, 0.1, 0.133, 0.2, 0.3, 0.4, 0.6, 0.8];
    if let Some(dir) = directory {
        std::fs::create_dir_all(dir)?;
        std::fs::write(dir.join("SCOPE.txt"),
            "Actual production HLSL; generated byte-validated backgrounds; synthetic time inputs.\n\
             PNG files are offscreen composites, not DWM captures or hardware timing evidence.\n\
             RGB means use encoded 8-bit channels. Contrast uses linear luminance.\n\
             Shape bounds are engineering regressions, not an exact fit to the iPhone recordings.\n\
             Full visual acceptance, native presentation and formal EXE self-test remain separate.\n")?;
    }
    let mut csv = match directory {
        Some(dir) => Some(std::fs::File::create(dir.join("entrance.csv"))?),
        None => None,
    };
    if let Some(file) = &mut csv {
        writeln!(file, "background,time_ms,body_r,body_g,body_b,opaque_text_pixels,min_text_contrast")?;
        file.flush()?;
    }
    let mask = crate::voice_window::content_mask(w, h, h as f32 / 26.0, Phase::Optimizing)?;
    let mut failures = Vec::new();
    let mut global_contrast = f64::INFINITY;
    for (kind, name) in [(0, "white"), (1, "black"), (2, "green")] {
        let mut p = AdaptivePipeline::new_voice(device.clone(), context.clone(), w, h, &mask)?;
        upload_fixture_checked(&p, &fixture(p.raw.width, p.raw.height, kind))?;
        let normal = p.shader.clone();
        let without_ink = shader(&p, "#define LIQUID_TEST_INK_OFF 1")?;
        let mut means = Vec::new();
        let mut previous_time = 0.0;
        // Keep all nine frames and metrics even when a shape/readability assertion
        // fails. Do not select just the best-looking frame from the sequence.
        for (index, &time) in times.iter().enumerate() {
            advance(&p, false, previous_time, time, Phase::Optimizing);
            previous_time = time;
            let foreground = p.read_rgba(&p.output)?;
            if let Some(dir) = directory {
                crate::png::write(&dir.join(format!("{name}-{index:02}-text.png")),
                    p.raw.width, p.raw.height, &p.composite_fixture()?)?;
            }
            p.shader = without_ink.clone();
            p.render_voice(false, time, Phase::Optimizing, 0.0, 1.0);
            let background = p.read_rgba(&p.output)?;
            let rgb = body_rgb(&background, w, h);
            means.push((rgb[0] + rgb[1] + rgb[2]) / 3.0);
            if let Some(dir) = directory {
                crate::png::write(&dir.join(format!("{name}-{index:02}-material.png")),
                    p.raw.width, p.raw.height, &p.composite_fixture()?)?;
            }
            p.shader = normal.clone();
            p.render_voice(false, time, Phase::Optimizing, 0.0, 1.0);
            ensure(foreground == p.read_rgba(&p.output)?,
                "Same-time ink ablation changed adaptive history")?;
            let (count, contrast) = text_contrast(&foreground, &background, &mask, w, h);
            if time >= 0.133 {
                if count <= 10 || contrast < 4.5 {
                    failures.push(format!("{name} at {time:.3}s: opaque text count={count}, contrast={contrast:.4}"));
                }
                if count > 0 { global_contrast = global_contrast.min(contrast); }
            }
            if kind == 2 && !(rgb[1] > rgb[0] + 50.0 && rgb[1] > rgb[2] + 25.0) {
                failures.push(format!("Green source lost chroma at {time:.3}s: {rgb:?}"));
            }
            let contrast_cell = if count == 0 { String::new() } else { format!("{contrast:.6}") };
            if let Some(file) = &mut csv {
                writeln!(file, "{name},{:.3},{:.4},{:.4},{:.4},{count},{contrast_cell}",
                    time * 1000.0, rgb[0], rgb[1], rgb[2])?;
                file.flush()?;
            }
            eprintln!("[white-entrance] {name} t={:.0}ms blank_rgb={rgb:.2?} opaque_text={count} contrast={contrast_cell}", time * 1000.0);
        }
        let lowest = means.iter().copied().fold(f64::INFINITY, f64::min);
        let highest = means.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        if kind == 0 {
            let crest = means[2..=5].iter().copied().fold(f64::INFINITY, f64::min);
            if means[0] < 245.0 || means[1] < 245.0 {
                failures.push("White entrance begins as a gray plate instead of a light surface".into());
            }
            if means[1] - crest < 12.0 || means[6] - crest < 10.0 {
                failures.push("White material lacks a measurable density crest followed by release".into());
            }
            // A late trough used to pass the peak-anywhere check above. Require
            // actual recovery at the next samples, not just a timed target that
            // acquires another low-pass lag. These are engineering shape bounds.
            if means[4] - means[3] < 4.0 || means[5] - means[4] < 8.0 || means[6] < 240.0 {
                failures.push(format!("White recovery remains delayed: 133/200/300/400ms={:.3}/{:.3}/{:.3}/{:.3}",
                    means[3], means[4], means[5], means[6]));
            }
            if means[7] < 245.0 || means[8] < 245.0 || (means[8] - means[7]).abs() > 3.0 {
                failures.push("White material has not returned to a near-white stable surface by 600-800ms".into());
            }
            if !(means[5] <= means[6] + 1.0 && means[6] <= means[7] + 1.0 && means[7] <= means[8] + 1.0) {
                failures.push("White material reverses brightness during the release tail".into());
            }
        } else if highest - lowest > 3.0 {
            failures.push(format!("{name} received an unwanted white-style blank-material pulse: range={:.4}", highest - lowest));
        }
        // Remove animated foreground from the stability comparison. A moving
        // optimizing icon must not be mistaken for material breathing.
        p.shader = without_ink;
        p.render_voice(false, 0.8, Phase::Activating, 0.0, 1.0);
        let held = p.read_rgba(&p.canvas)?;
        advance(&p, false, 0.8, 1.6, Phase::Activating);
        let drift = max_diff(&held, &p.read_rgba(&p.canvas)?);
        if drift > 1 { failures.push(format!("{name} material still drifts after 800ms: max byte difference={drift}")); }
    }
    // Accessibility mode skips the entire transient, not just its geometry.
    let p = AdaptivePipeline::new_voice(device, context, w, h, &vec![0u8; (w * h) as usize])?;
    p.inner.reduced_motion.set(true);
    upload_fixture_checked(&p, &fixture(p.raw.width, p.raw.height, 0))?;
    p.render_voice(false, 0.0, Phase::Activating, 0.0, 1.0);
    let first = p.read_rgba(&p.canvas)?;
    for &time in &times[1..] {
        p.render_voice(false, time, Phase::Activating, 0.0, 1.0);
        if first != p.read_rgba(&p.canvas)? {
            failures.push(format!("Reduced motion still pulses at {time:.3}s"));
        }
    }
    let report = if failures.is_empty() {
        format!("PASS: 27 entrance samples; white crest/release; black/green controls; per-frame text contrast >=4.5 from 133ms; measured minimum={global_contrast:.6}; held-material and reduced-motion checks.\nNot final visual or native-window acceptance.\n")
    } else { format!("FAIL:\n{}\n", failures.join("\n")) };
    if let Some(dir) = directory { std::fs::write(dir.join("result.txt"), &report)?; }
    ensure(failures.is_empty(), &report)?;
    eprintln!("[white-entrance] PASS; 27 actual-HLSL samples; contrast minimum={global_contrast:.6}; generated inputs only");
    Ok(())
}

#[cfg(test)]
#[test]
fn white_entrance_resolves_and_stays_readable() { unsafe {
    let directory = std::env::var_os("GLASS_MATERIAL_FIXTURES")
        .map(|p| std::path::PathBuf::from(p).with_extension("white-entrance"));
    verify(directory.as_deref()).unwrap();
} }
